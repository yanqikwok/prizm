#!/usr/bin/env tsx
/**
 * Generate the PRIZM Alignment Checker's ground truth from PRIZM's canonical
 * sources, so the checker never drifts as components, tokens, or the extension
 * packs change.
 *
 * Sources of truth:
 *   - app/globals.css `@theme`            → legal semantic colour tokens + radii
 *   - styles/tokens/baseline.css          → radius px values + banned primitive scales
 *   - lib/components-registry.ts          → the web + JavaFX component catalogue
 *   - lib/javafx-api.ts, rc3-javafx-api.ts → native JavaFX class → Prizm* control map
 *
 * Writes lib/alignment-ground-truth.generated.ts, which lib/alignment-checker.ts
 * imports. Run after any change to the sources above:
 *
 *   pnpm generate:alignment          # regenerate the file
 *   pnpm generate:alignment --check  # fail (exit 1) if the file is stale (CI/pre-commit)
 *
 * The --check mode compares extracted DATA (not formatting), so it is immune to
 * Biome reformatting the generated file.
 */

import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { type UiSignature, extractSignature } from "../lib/alignment-fidelity";
import { COMPONENTS } from "../lib/components-registry";
import { JAVAFX_API } from "../lib/javafx-api";
import { RC3_JAVAFX_API } from "../lib/rc3-javafx-api";

const ROOT = resolve(import.meta.dirname, "..");
const OUT = resolve(ROOT, "lib/alignment-ground-truth.generated.ts");
const BASELINE_OUT = resolve(ROOT, "lib/prizm-baseline.generated.ts");

interface Baseline {
  ref: string;
  signatures: Record<string, UiSignature>;
}

/** Extract A3 baseline: a style signature per PRIZM components/ui/* file. */
function extractBaseline(): Baseline {
  const uiDir = resolve(ROOT, "components/ui");
  const signatures: Record<string, UiSignature> = {};
  for (const file of readdirSync(uiDir)
    .filter((f) => f.endsWith(".tsx"))
    .sort()) {
    const slug = file.replace(/\.tsx$/, "");
    signatures[slug] = extractSignature(readFileSync(resolve(uiDir, file), "utf8"));
  }
  // Use the package version (stable) rather than the git SHA (which would churn
  // the generated file on every commit and trigger spurious "checker updated" notices).
  const version = JSON.parse(readFileSync(resolve(ROOT, "package.json"), "utf8")).version;
  return { ref: `v${version}`, signatures };
}

function renderBaseline(b: Baseline): string {
  const entries = Object.keys(b.signatures)
    .sort()
    .map((slug) => `  ${JSON.stringify(slug)}: ${JSON.stringify(b.signatures[slug])},`)
    .join("\n");
  return `// AUTO-GENERATED by scripts/generate-alignment-groundtruth.ts — DO NOT EDIT BY HAND.
// Regenerate with: pnpm generate:alignment
//
// A3 fidelity baseline: a style signature per PRIZM components/ui/* file, used to
// detect drift in components a product has copied. Generated from this PRIZM build.

import type { UiSignature } from "./alignment-fidelity";

/** The PRIZM version these baseline signatures were taken from. */
export const PRIZM_BASELINE_REF = ${JSON.stringify(b.ref)};

/** slug → style signature of PRIZM's own components/ui/<slug>.tsx. */
export const PRIZM_UI_SIGNATURES: Record<string, UiSignature> = {
${entries}
};
`;
}

interface GroundTruth {
  colorTokens: string[];
  radiusTokens: string[];
  radiusPx: number[];
  primitiveFamilies: string[];
  components: Array<{ name: string; slug: string; status: string; javafx: boolean }>;
  javafxControlMap: Record<string, string>;
}

function readCss(rel: string): string {
  return readFileSync(resolve(ROOT, rel), "utf8");
}

/** Pull the contents of the `@theme { … }` block from globals.css. */
function themeBlock(css: string): string {
  const start = css.indexOf("@theme");
  if (start === -1) return "";
  const open = css.indexOf("{", start);
  let depth = 0;
  for (let i = open; i < css.length; i++) {
    if (css[i] === "{") depth++;
    else if (css[i] === "}") {
      depth--;
      if (depth === 0) return css.slice(open + 1, i);
    }
  }
  return "";
}

function extract(): GroundTruth {
  const globals = readCss("app/globals.css");
  const baseline = readCss("styles/tokens/baseline.css");
  const theme = themeBlock(globals);

  // Legal semantic colour tokens: @theme --color-<name>
  const colorTokens = uniqueSorted(
    [...theme.matchAll(/--color-([a-z][a-z-]*)\s*:/g)].map((m) => m[1]),
  );

  // Radius token names: @theme --radius-<name>
  const radiusTokens = uniqueSorted([...theme.matchAll(/--radius-([a-z]+)\s*:/g)].map((m) => m[1]));

  // Radius px values from baseline (--prizm-radius-*: Xrem), plus 0 (none).
  const radiusPx = uniqueSorted(
    [
      0,
      ...[...baseline.matchAll(/--prizm-radius-[a-z]+\s*:\s*([\d.]+)rem/g)].map((m) =>
        Math.round(Number(m[1]) * 16),
      ),
    ],
    (a, b) => a - b,
  ) as number[];

  // Primitive colour scales (--prizm-<family>-<num>) across every token file,
  // including the extension packs (e.g. rc3): banned for direct use in product code.
  const tokenDir = resolve(ROOT, "styles/tokens");
  const allTokenCss = readdirSync(tokenDir)
    .filter((f) => f.endsWith(".css"))
    .map((f) => readFileSync(resolve(tokenDir, f), "utf8"))
    .join("\n");
  const primitiveFamilies = uniqueSorted(
    [...allTokenCss.matchAll(/--prizm-([a-z][a-z0-9]*)-\d{2,3}\b/g)].map((m) => m[1]),
  );

  // Component catalogue from the registry.
  const components = COMPONENTS.map((c) => ({
    name: c.name,
    slug: c.slug,
    status: c.status,
    javafx: Boolean(c.javafx),
  })).sort((a, b) => a.slug.localeCompare(b.slug));

  // Native JavaFX control → Prizm* control map (control.* bases only).
  const javafxControlMap: Record<string, string> = {};
  for (const api of [...Object.values(JAVAFX_API), ...Object.values(RC3_JAVAFX_API)]) {
    if (!api.base || !api.base.startsWith("javafx.scene.control.")) continue;
    const nativeShort = (api.base.split(".").pop() as string).replace(/<.*>/, "");
    const prizmClass = api.className.replace(/<.*>/, "");
    if (!javafxControlMap[nativeShort]) javafxControlMap[nativeShort] = prizmClass;
  }

  return { colorTokens, radiusTokens, radiusPx, primitiveFamilies, components, javafxControlMap };
}

function uniqueSorted<T>(arr: T[], cmp?: (a: T, b: T) => number): T[] {
  return [...new Set(arr)].sort(cmp ?? ((a, b) => String(a).localeCompare(String(b))));
}

function render(gt: GroundTruth): string {
  const controls = Object.keys(gt.javafxControlMap)
    .sort()
    .map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(gt.javafxControlMap[k])},`)
    .join("\n");
  const components = gt.components
    .map(
      (c) =>
        `  { name: ${JSON.stringify(c.name)}, slug: ${JSON.stringify(c.slug)}, status: ${JSON.stringify(c.status)}, javafx: ${c.javafx} },`,
    )
    .join("\n");
  return `// AUTO-GENERATED by scripts/generate-alignment-groundtruth.ts — DO NOT EDIT BY HAND.
// Regenerate with: pnpm generate:alignment
//
// Ground truth for the PRIZM Alignment Checker, derived from PRIZM's canonical
// sources (globals.css @theme, styles/tokens/baseline.css, components-registry.ts,
// javafx-api.ts, rc3-javafx-api.ts). Keeps the checker in sync as PRIZM evolves.

export interface PrizmComponentEntry {
  name: string;
  slug: string;
  status: string;
  javafx: boolean;
}

/** Legal semantic colour token suffixes (bg, surface, fg, accent, …). */
export const LEGAL_COLOR_TOKENS: string[] = ${JSON.stringify(gt.colorTokens)};

/** Legal radius token names (xs … xl). */
export const LEGAL_RADIUS_TOKENS: string[] = ${JSON.stringify(gt.radiusTokens)};

/** Legal radius values in px (0 + the token scale). */
export const LEGAL_RADIUS_PX: number[] = ${JSON.stringify(gt.radiusPx)};

/** PRIZM baseline primitive colour scales — banned for direct use in product code. */
export const PRIZM_PRIMITIVE_FAMILIES: string[] = ${JSON.stringify(gt.primitiveFamilies)};

/** The full PRIZM component catalogue. */
export const PRIZM_COMPONENTS: PrizmComponentEntry[] = [
${components}
];

/** Native JavaFX control class → the Prizm* control that replaces it. */
export const JAVAFX_CONTROL_MAP: Record<string, string> = {
${controls}
};

/** Quick counts, handy for the checker's "kept in sync" note. */
export const GROUND_TRUTH_SUMMARY = {
  colorTokens: ${gt.colorTokens.length},
  components: ${gt.components.length},
  javafxControls: ${Object.keys(gt.javafxControlMap).length},
};
`;
}

/** Normalise to a formatting-immune shape for comparison. */
function canonical(gt: GroundTruth): string {
  return JSON.stringify({
    colorTokens: [...gt.colorTokens].sort(),
    radiusTokens: [...gt.radiusTokens].sort(),
    radiusPx: [...gt.radiusPx].sort((a, b) => a - b),
    primitiveFamilies: [...gt.primitiveFamilies].sort(),
    components: [...gt.components].sort((a, b) => a.slug.localeCompare(b.slug)),
    javafxControlMap: Object.fromEntries(
      Object.entries(gt.javafxControlMap).sort(([a], [b]) => a.localeCompare(b)),
    ),
  });
}

const STALE_MSG =
  "✗ Alignment checker is out of date with PRIZM.\n" +
  "  PRIZM components/tokens/extension packs changed but the checker wasn't regenerated.\n" +
  "  Fix: pnpm generate:alignment  (then commit the updated files)";

async function main() {
  const check = process.argv.includes("--check");
  const gt = extract();
  const baseline = extractBaseline();

  if (check) {
    // Compare DATA against the committed modules (immune to Biome reformatting).
    if (!existsSync(OUT) || !existsSync(BASELINE_OUT)) {
      console.error("✗ Generated alignment files are missing. Run: pnpm generate:alignment");
      process.exit(1);
    }
    let gtMod: {
      LEGAL_COLOR_TOKENS: string[];
      LEGAL_RADIUS_TOKENS: string[];
      LEGAL_RADIUS_PX: number[];
      PRIZM_PRIMITIVE_FAMILIES: string[];
      PRIZM_COMPONENTS: GroundTruth["components"];
      JAVAFX_CONTROL_MAP: Record<string, string>;
    };
    let baseMod: { PRIZM_UI_SIGNATURES: Record<string, UiSignature> };
    try {
      gtMod = await import(`${pathToFileURL(OUT).href}?t=${Date.now()}`);
      baseMod = await import(`${pathToFileURL(BASELINE_OUT).href}?t=${Date.now()}`);
    } catch {
      console.error("✗ Generated alignment files are unreadable. Run: pnpm generate:alignment");
      process.exit(1);
    }
    const committedGt = canonical({
      colorTokens: gtMod.LEGAL_COLOR_TOKENS ?? [],
      radiusTokens: gtMod.LEGAL_RADIUS_TOKENS ?? [],
      radiusPx: gtMod.LEGAL_RADIUS_PX ?? [],
      primitiveFamilies: gtMod.PRIZM_PRIMITIVE_FAMILIES ?? [],
      components: gtMod.PRIZM_COMPONENTS ?? [],
      javafxControlMap: gtMod.JAVAFX_CONTROL_MAP ?? {},
    });
    const sigsEqual =
      JSON.stringify(baseMod.PRIZM_UI_SIGNATURES ?? {}) === JSON.stringify(baseline.signatures);
    if (committedGt !== canonical(gt) || !sigsEqual) {
      console.error(STALE_MSG);
      process.exit(1);
    }
    console.log("✓ Alignment checker (ground truth + fidelity baseline) is in sync with PRIZM.");
    return;
  }

  writeFileSync(OUT, render(gt));
  writeFileSync(BASELINE_OUT, renderBaseline(baseline));
  console.log(
    `✓ Wrote alignment ground truth (${gt.colorTokens.length} colour tokens, ${gt.components.length} components, ${Object.keys(gt.javafxControlMap).length} JavaFX controls) + fidelity baseline (${Object.keys(baseline.signatures).length} components @ ${baseline.ref}).`,
  );
}

main();
